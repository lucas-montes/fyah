/// Supported version control systems.
#[derive(Debug, Clone, Copy, PartialEq, Valuable, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum VcsType {
    /// Git.
    Git,
    /// Jujutsu (using change ID for stability across rebases).
    Jj,
    /// Mercurial.
    Hg,
    /// Subversion.
    Svn,
}

/// Version control system information for a trace.
#[derive(Debug, Clone, PartialEq, Valuable, Serialize, Deserialize)]
pub struct VcsInfo {
    /// The VCS type.
    #[serde(rename = "type")]
    vcs_type: VcsType,
    /// Revision identifier (git commit SHA, jj change ID, hg changeset, etc.).
    revision: String,
}

impl VcsInfo {
    /// Create new VCS information.
    pub fn new(vcs_type: VcsType, revision: impl Into<String>) -> Self {
        Self {
            vcs_type,
            revision: revision.into(),
        }
    }
}

