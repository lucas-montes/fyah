/// The tool that generated this trace.
///
/// Named `AgentToolInfo` to avoid collision with the existing
/// [`Tool`](crate::tools::types::Tool) enum in the codebase.
#[derive(Debug, Clone, PartialEq, Valuable, Serialize, Deserialize)]
pub struct AgentToolInfo {
    /// Tool name (e.g. `"cursor"`, `"claude"`, `"fyah"`).
    #[serde(skip_serializing_if = "Option::is_none")]
    name: Option<String>,
    /// Tool version (e.g. `"2.4.0"`).
    #[serde(skip_serializing_if = "Option::is_none")]
    version: Option<String>,
}

impl AgentToolInfo {
    /// Create a new empty tool info (no name or version set).
    pub fn new() -> Self {
        Self {
            name: None,
            version: None,
        }
    }

    /// Set the tool name (builder pattern).
    pub fn with_name(mut self, name: impl Into<String>) -> Self {
        self.name = Some(name.into());
        self
    }

    /// Set the tool version (builder pattern).
    pub fn with_version(mut self, version: impl Into<String>) -> Self {
        self.version = Some(version.into());
        self
    }
}

impl Default for AgentToolInfo {
    fn default() -> Self {
        Self::new()
    }
}

