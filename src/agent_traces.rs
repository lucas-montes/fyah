/// A line range within a file, attributed to a conversation.
///
/// Line numbers are 1-indexed and reference positions at the recorded
/// VCS revision.
#[derive(Debug, Clone, PartialEq, Valuable, Serialize, Deserialize)]
pub struct RangeEntry {
    /// Start line number (1-indexed).
    start_line: u32,
    /// End line number (1-indexed, inclusive).
    end_line: u32,
    /// Hash of the attributed content for position-independent tracking.
    /// Format: `"<algorithm>:<hex>"` (e.g. `"murmur3:9f2e8a1b"`).
    #[serde(skip_serializing_if = "Option::is_none")]
    content_hash: Option<String>,
    /// Per-range contributor override (e.g. for agent handoffs).
    #[serde(skip_serializing_if = "Option::is_none")]
    contributor: Option<Contributor>,
}

impl RangeEntry {
    /// Create a new line range (1-indexed, inclusive).
    pub fn new(start_line: u32, end_line: u32) -> Self {
        Self {
            start_line,
            end_line,
            content_hash: None,
            contributor: None,
        }
    }

    /// Set the content hash (builder pattern).
    pub fn with_content_hash(mut self, hash: impl Into<String>) -> Self {
        self.content_hash = Some(hash.into());
        self
    }

    /// Set the per-range contributor override (builder pattern).
    pub fn with_contributor(mut self, contributor: Contributor) -> Self {
        self.contributor = Some(contributor);
        self
    }
}

/// A link to a related resource (session, prompt, etc.).
#[derive(Debug, Clone, PartialEq, Valuable, Serialize, Deserialize)]
pub struct RelatedResource {
    /// The type of relationship (e.g. `"session"`, `"prompt"`).
    #[serde(rename = "type")]
    resource_type: String,
    /// URL to the related resource.
    url: String,
}

impl RelatedResource {
    /// Create a new related resource link.
    pub fn new(resource_type: impl Into<String>, url: impl Into<String>) -> Self {
        Self {
            resource_type: resource_type.into(),
            url: url.into(),
        }
    }
}

/// A conversation that contributed code to a file.
///
/// Groups one or more line ranges under a single contributor and optional
/// URL pointing to the conversation that produced them.
#[derive(Debug, Clone, PartialEq, Valuable, Serialize, Deserialize)]
pub struct Conversation {
    /// URL to look up the conversation that produced this code.
    #[serde(skip_serializing_if = "Option::is_none")]
    url: Option<String>,
    /// The contributor for ranges in this conversation (can be overridden
    /// per-range).
    #[serde(skip_serializing_if = "Option::is_none")]
    contributor: Option<Contributor>,
    /// Line ranges produced by this conversation.
    ranges: Vec<RangeEntry>,
    /// Other related resources (sessions, prompts, etc.).
    #[serde(skip_serializing_if = "Option::is_none")]
    related: Option<Vec<RelatedResource>>,
}

impl Conversation {
    /// Create a new conversation with the given line ranges.
    pub fn new(ranges: Vec<RangeEntry>) -> Self {
        Self {
            url: None,
            contributor: None,
            ranges,
            related: None,
        }
    }

    /// Set the conversation URL (builder pattern).
    pub fn with_url(mut self, url: impl Into<String>) -> Self {
        self.url = Some(url.into());
        self
    }

    /// Set the conversation-level contributor (builder pattern).
    pub fn with_contributor(mut self, contributor: Contributor) -> Self {
        self.contributor = Some(contributor);
        self
    }

    /// Set related resources (builder pattern).
    pub fn with_related(mut self, related: Vec<RelatedResource>) -> Self {
        self.related = Some(related);
        self
    }
}

