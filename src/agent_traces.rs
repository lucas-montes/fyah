/// A file with attributed ranges.
#[derive(Debug, Clone, PartialEq, Valuable, Serialize, Deserialize)]
pub struct FileEntry {
    /// Relative file path from repository root.
    path: String,
    /// Conversations that contributed to this file.
    conversations: Vec<Conversation>,
}

impl FileEntry {
    /// Create a new file entry with the given path and no conversations.
    pub fn new(path: impl Into<String>) -> Self {
        Self {
            path: path.into(),
            conversations: vec![],
        }
    }

    /// Set conversations (builder pattern).
    pub fn with_conversations(mut self, conversations: Vec<Conversation>) -> Self {
        self.conversations = conversations;
        self
    }
}

